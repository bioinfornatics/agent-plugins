import { cpSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const dist=path.join(root,"dist");
if(path.dirname(dist)!==root||path.basename(dist)!=="dist")throw new Error("refusing to clean an unsafe dist path");
const retired=path.join(root,`.dist-retired-${process.pid}`);
rmSync(retired,{recursive:true,force:true});
if(existsSync(dist))renameSync(dist,retired);
rmSync(retired,{recursive:true,force:true});
const viewer=readFileSync(path.join(root,"eval-viewer","viewer.html"),"utf8");
writeFileSync(path.join(root,"eval-viewer","embedded_viewer.ts"),`/** Generated from viewer.html by scripts/build.mjs. Do not edit directly. */\nexport const EMBEDDED_VIEWER_HTML = ${JSON.stringify(viewer)};\n`);
const tsc=path.join(root,"node_modules","typescript","bin","tsc");
const result=spawnSync(process.execPath,[tsc,"-p",path.join(root,"tsconfig.json")],{cwd:root,stdio:"inherit"});
if(result.status!==0)process.exit(result.status??1);
mkdirSync(path.join(dist,"eval-viewer"),{recursive:true});
cpSync(path.join(root,"eval-viewer","viewer.html"),path.join(dist,"eval-viewer","viewer.html"));
